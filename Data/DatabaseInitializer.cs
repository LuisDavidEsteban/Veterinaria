using Npgsql;

namespace ControlClinicoVeterinario.Data;

/// <summary>
/// Prepara la base de datos al arrancar la aplicación:
/// 1) crea la base de datos si no existe y 2) ejecuta el DDL idempotente de las tablas.
/// </summary>
public static class DatabaseInitializer
{
    private const string Ddl = @"
CREATE TABLE IF NOT EXISTS clientes (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL,
    telefono   VARCHAR(30),
    direccion  VARCHAR(250),
    correo     VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS mascotas (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    especie     VARCHAR(50)  NOT NULL,
    raza        VARCHAR(100),
    edad        INTEGER       NOT NULL DEFAULT 0 CHECK (edad >= 0),
    peso        NUMERIC(6,2)  NOT NULL DEFAULT 0 CHECK (peso >= 0),
    cliente_id  INTEGER       NOT NULL,
    CONSTRAINT fk_mascotas_clientes FOREIGN KEY (cliente_id)
        REFERENCES clientes (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS consultas (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        TIMESTAMP     NOT NULL DEFAULT NOW(),
    motivo       VARCHAR(250)  NOT NULL,
    diagnostico  TEXT,
    tratamiento  TEXT,
    mascota_id   INTEGER       NOT NULL,
    CONSTRAINT fk_consultas_mascotas FOREIGN KEY (mascota_id)
        REFERENCES mascotas (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_mascotas_cliente_id  ON mascotas (cliente_id);
CREATE INDEX IF NOT EXISTS ix_consultas_mascota_id ON consultas (mascota_id);
";

    /// <summary>Ejecuta la inicialización completa. Lanza excepción si no logra conectarse.</summary>
    public static void Inicializar()
    {
        CrearBaseDeDatosSiNoExiste();

        using var conexion = Conexion.CrearConexion();
        using var transaccion = conexion.BeginTransaction();
        using (var comando = new NpgsqlCommand(Ddl, conexion, transaccion))
        {
            comando.ExecuteNonQuery();
        }
        transaccion.Commit();
    }

    /// <summary>
    /// Se conecta a la base de mantenimiento <c>postgres</c> y crea la base configurada si aún no existe.
    /// </summary>
    private static void CrearBaseDeDatosSiNoExiste()
    {
        var builder = Conexion.Builder;
        var nombreBase = builder.Database;
        if (string.IsNullOrWhiteSpace(nombreBase))
        {
            throw new InvalidOperationException("La cadena de conexión no especifica 'Database'.");
        }

        builder.Database = "postgres";
        builder.Pooling = false;

        using var conexion = new NpgsqlConnection(builder.ConnectionString);
        conexion.Open();

        using (var existe = new NpgsqlCommand("SELECT 1 FROM pg_database WHERE datname = @nombre", conexion))
        {
            existe.Parameters.AddWithValue("@nombre", nombreBase);
            if (existe.ExecuteScalar() != null)
            {
                return;
            }
        }

        // Los identificadores no admiten parámetros: se escapan las comillas dobles manualmente.
        var identificador = "\"" + nombreBase.Replace("\"", "\"\"") + "\"";
        using var crear = new NpgsqlCommand($"CREATE DATABASE {identificador} ENCODING 'UTF8'", conexion);
        crear.ExecuteNonQuery();
    }
}
